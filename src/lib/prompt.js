function buildUserPrompt({ rawText, metadata, files, truncated }) {
  const safeMetadata = {
    title: metadata?.title || null,
    type: metadata?.type || null,
    university: metadata?.university || null,
    owner: metadata?.owner || null,
  };

  return `بيانات الإدخال التي أدخلها المستخدم يدويًا:
${JSON.stringify(safeMetadata, null, 2)}

قائمة الملفات الأصلية:
${JSON.stringify(files || [], null, 2)}

ملاحظة المعالجة:
${truncated ? "تم اختصار النص بسبب حد الحجم؛ قد تكون بعض التفاصيل غير موجودة." : "تم تمرير النص المتاح كاملًا ضمن حد النظام."}

نصوص المشروع المستخرجة من الملفات:
<PROJECT_SOURCE>
${rawText}
</PROJECT_SOURCE>

استخرج بيانات المشروع فقط وفق المخطط المحدد. استخدم البيانات اليدوية لتثبيت الاسم أو الجهة أو صاحب المشروع عند ذكرها، لكن لا تحولها إلى دليل على نتائج أو شراكات أو ملكية فكرية.`;
}

